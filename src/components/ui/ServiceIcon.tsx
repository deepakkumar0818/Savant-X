const FALLBACK: LucideIcon = Sparkles;

function iconForEmoji(emoji: string | undefined | null): LucideIcon {
  if (!emoji) return FALLBACK;
  const key = emoji.trim();
  return EMOJI_ICONS[key] ?? EMOJI_ICONS[key.replace(/️/g, '')] ?? FALLBACK;
}

type Props = {
  /** The emoji stored in the page data; rendered as a matching line icon. */
  emoji: string | undefined | null;
  /** Tile size. `none` renders only the glyph (for inline use). */
  size?: 'none' | 'sm' | 'md' | 'lg';
  /** Light tile (default) for white backgrounds, or `inverse` for dark/gradient backgrounds. */
  tone?: 'light' | 'inverse';
  className?: string;
};

const TILE: Record<Exclude<Props['size'], undefined | 'none'>, { box: string; glyph: string }> = {
  sm: { box: 'h-8 w-8 rounded-lg', glyph: 'h-4 w-4' },
  md: { box: 'h-11 w-11 rounded-xl', glyph: 'h-5 w-5' },
  lg: { box: 'h-14 w-14 rounded-2xl', glyph: 'h-7 w-7' },
};

export default function ServiceIcon({ emoji, size = 'md', tone = 'light', className = '' }: Props) {
  const Icon = iconForEmoji(emoji);

  if (size === 'none') {
    // Default to the surrounding text size unless the caller sets an explicit size.
    const sizing = /(^|\s)h-/.test(className) ? '' : 'h-[1em] w-[1em] align-[-0.125em]';
    return <Icon className={`inline-block shrink-0 ${sizing} ${className}`} strokeWidth={1.75} aria-hidden />;
  }

  const { box, glyph } = TILE[size];
  const toneClass =
    tone === 'inverse'
      ? 'bg-white/15 text-white ring-1 ring-white/25'
      : 'bg-gradient-to-br from-indigo-50 to-blue-50 text-indigo-600 ring-1 ring-indigo-100';

  return (
    <span className={`inline-flex shrink-0 items-center justify-center ${box} ${toneClass} ${className}`} aria-hidden>
      <Icon className={glyph} strokeWidth={1.75} />
    </span>
  );
}
